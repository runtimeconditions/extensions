class ConformanceTest {
    static List<String> cases() {
        return TestSupport.cases();
    }

    @ParameterizedTest
    @MethodSource("cases")
    void emitsVerifiesAndCompilesUnderStrictJavac(String name) throws IOException {
        Path workspace = temporaryDirectory();
        try {
            Built built = buildCase(name, workspace, null);
            Verification.verifyPackage(built.plan(), built.directory(), built.model());
            writeConformance(built);
            Compiled compiled = compileBuilt(built, workspace.resolve("classes"));
            assertTrue(compiled.success(), compiled.output());
            assertFalse(Verification.apiSurface(built.directory()).isEmpty());
        } finally {
            delete(workspace);
        }
    }

    @ParameterizedTest
    @MethodSource("cases")
    void threeIndependentEmissionsAreByteIdentical(String name) {
        ObjectNode model = Model.load(modelPath(name));
        List<Map<String, String>> runs = new ArrayList<>();
        Path workspace = temporaryDirectory();
        try {
            for (int run = 0; run < 3; run += 1) {
                EmissionPlan plan = planFor(model, name);
                Path directory = workspace.resolve("run-" + run);
                Source.emitPackage(plan, model, directory);
                runs.add(snapshot(directory));
            }
            assertEquals(runs.get(0), runs.get(1));
            assertEquals(runs.get(0), runs.get(2));
            for (Map.Entry<String, String> entry : runs.get(0).entrySet()) {
                if (entry.getKey().endsWith(".java")) {
                    assertTrue(
                            entry.getValue().startsWith("// Code generated by runtimeconditions-binding-emitter-java 0.1.0 from model "),
                            entry.getKey());
                    assertTrue(entry.getValue().split("\n")[0].endsWith("DO NOT EDIT."), entry.getKey());
                    assertFalse(entry.getValue().contains("\t"), entry.getKey());
                    assertTrue(entry.getValue().endsWith("}\n"), entry.getKey());
                }
            }
        } finally {
            delete(workspace);
        }
    }

    @Test
    void theEmitterOutputContainsExactlyTheDeclaredPackageFiles() {
        Path workspace = temporaryDirectory();
        try {
            Built built = buildCase("01-owned-kind-interface", workspace, null);
            String base = "src/main/java/io/runtimeconditions/conformance/c01ownedkindinterface/";
            assertEquals(
                    List.of(
                            "pom.xml",
                            base + "Bindings.java",
                            base + "Declaration.java",
                            base + "Http.java",
                            base + "Region.java",
                            base + "ServiceField.java",
                            "src/main/resources/runtimeconditions/runtimeconditions.bindings.yaml"),
                    new ArrayList<>(snapshot(built.directory()).keySet()));
        } finally {
            delete(workspace);
        }
    }

    private static String probe(Built built, Path classes, String line) throws IOException {
        Path file = built.directory().resolve(Source.sourcePath(built.plan(), "Probe"));
        Files.writeString(
                file,
                "package " + built.plan().target().javaPackage() + ";\n"
                        + "@SuppressWarnings(\"unused\")\n"
                        + "final class Probe {\n    static void probe() {\n        " + line + "\n    }\n}\n");
        Compiled compiled = compileBuilt(built, classes);
        Files.delete(file);
        return compiled.success() ? "" : compiled.output();
    }

    @Test
    void generatedTypesRejectValuesTheModelDoesNotAllow() throws IOException {
        Path workspace = temporaryDirectory();
        try {
            Built built = buildCase("10-scoped-domains-collisions", workspace, null);
            String wrongValue = built.plan().types().stream().filter(item -> item.kind() == Plan.Kind.ENUM).findFirst().orElseThrow().name();
            String scalar = built.plan().types().stream().filter(item -> item.name().equals("BaseUrl")).findFirst().orElseThrow().name();
            String[][] probes = {
                {"wrong enum value", wrongValue + " _x = \"streaming\";"},
                {"wrong scalar type", scalar + " _x = new " + scalar + "(1L);"},
                {"missing required field", scalar + " _x = new " + scalar + "();"},
                {"non-field argument to a declaration", "Declaration _x = Bindings.service(\"x\");"},
            };
            for (String[] item : probes) {
                assertNotEquals("", probe(built, workspace.resolve("classes-" + item[0].replace(' ', '-')), item[1]), item[0] + " should not compile");
            }
            assertEquals("", probe(built, workspace.resolve("classes-ok"), "Declaration _x = Bindings.service(new " + scalar + "(\"x\"));"));
        } finally {
            delete(workspace);
        }
    }

    @Test
    void requiredValuesAreEnforcedAtRuntime() throws Exception {
        Path workspace = temporaryDirectory();
        try {
            Built built = buildCase("01-owned-kind-interface", workspace, null);
            Path classes = workspace.resolve("classes");
            Compiled compiled = compileBuilt(built, classes);
            assertTrue(compiled.success(), compiled.output());
            try (URLClassLoader loader = new URLClassLoader(new URL[] {classes.toUri().toURL()})) {
                Class<?> http = loader.loadClass(built.plan().target().javaPackage() + ".Http");
                Object value = http.getConstructor(String.class).newInstance("https://orders.internal");
                assertEquals("https://orders.internal", http.getMethod("endpoint").invoke(value));
                var error = org.junit.jupiter.api.Assertions.assertThrows(
                        java.lang.reflect.InvocationTargetException.class, () -> http.getConstructor(String.class).newInstance((Object) null));
                assertTrue(error.getCause() instanceof NullPointerException);
                assertEquals("endpoint", error.getCause().getMessage());
            }
        } finally {
            delete(workspace);
        }
    }

    @Test
    void anAdditiveFieldTypeIsCheckedAgainstTheProvidersMarker() {
        Path workspace = temporaryDirectory();
        Path mismatchedWorkspace = temporaryDirectory();
        try {
            Built built = buildCase("02-additive-field", workspace, null);
            Compiled compiled = compileBuilt(built, workspace.resolve("classes"));
            assertTrue(compiled.success(), compiled.output());
            Built mismatched = buildCase("02-additive-field", mismatchedWorkspace, "rcMarker_0000000000000000");
            Compiled failed = compileBuilt(mismatched, mismatchedWorkspace.resolve("classes"));
            assertFalse(failed.success());
            assertTrue(failed.output().contains("rcMarker_"), failed.output());
        } finally {
            delete(workspace);
            delete(mismatchedWorkspace);
        }
    }
}
