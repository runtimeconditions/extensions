public final class Metadata {
    public static final String EMITTER_NAME = property("name");
    public static final String EMITTER_VERSION = property("version");
    public static final String MANIFEST_PATH = "src/main/resources/runtimeconditions/runtimeconditions.bindings.yaml";

    private Metadata() {}

    /** Reads the emitter's identity from {@code emitter.properties}, which Gradle fills from the build. */
    private static String property(String key) {
        try (InputStream stream = Metadata.class.getResourceAsStream("/emitter.properties")) {
            Properties properties = new Properties();
            properties.load(Objects.requireNonNull(stream));
            return properties.getProperty(key);
        } catch (IOException | NullPointerException error) {
            throw new ExceptionInInitializerError("emitter.properties is unavailable");
        }
    }

    public static String header(JsonNode model) {
        return "Code generated by "
                + EMITTER_NAME
                + " "
                + EMITTER_VERSION
                + " from model "
                + model.path("metadata").path("semanticSha256").asText()
                + "; DO NOT EDIT.";
    }

    static String dependencyVersion(Dependency dependency) {
        return dependency.versionRange() != null
                ? dependency.versionRange()
                : dependencyInterval(dependency.version(), dependency.extension());
    }

    /** The target schema has already checked {@code value} as a semantic version. */
    static String dependencyInterval(String value, String coordinate) {
        String[] parts = value.split("[.-]");
        int major = Integer.parseInt(parts[0]);
        int minor = Integer.parseInt(parts[1]);
        String next = major == 0 ? "0." + (minor + 1) + ".0" : (major + 1) + ".0.0";
        return "[" + value + "," + next + ")";
    }

    private static String xml(String value) {
        return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    }

    private static String pom(EmissionPlan plan, JsonNode model) {
        PackageTarget target = plan.target();
        Set<String> coordinates = new HashSet<>();
        for (Dependency dependency : target.dependencies()) {
            if (!coordinates.add(dependency.coordinate())) {
                throw fail(
                        "package-config",
                        "RCJ1006",
                        target.packageKey(),
                        "multiple direct extensions use the same Maven coordinate",
                        "/dependencies");
            }
        }
        List<Dependency> dependencies = new ArrayList<>(target.dependencies());
        dependencies.sort(Comparator.comparing(Dependency::coordinate));
        String repository = target.repositoryUrl().endsWith(".git") ? target.repositoryUrl() : target.repositoryUrl() + ".git";
        StringBuilder items = new StringBuilder();
        for (Dependency dependency : dependencies) {
            items.append(
                    Templates.fill(
                            "dependency.xml.tmpl",
                            Templates.read("dependency.xml.tmpl"),
                            Map.of(
                                    "groupId", xml(dependency.groupId()),
                                    "artifactId", xml(dependency.artifactId()),
                                    "version", xml(dependencyVersion(dependency)))));
        }
        String block =
                dependencies.isEmpty()
                        ? ""
                        : Templates.fill("dependencies.xml.tmpl", Templates.read("dependencies.xml.tmpl"), Map.of("items", items.toString()));
        return Templates.fill(
                "pom.xml.tmpl",
                Templates.read("pom.xml.tmpl"),
                Map.of(
                        "header", header(model),
                        "groupId", xml(target.groupId()),
                        "artifactId", xml(target.artifactId()),
                        "version", xml(target.version()),
                        "repositoryUrl", xml(target.repositoryUrl()),
                        "scmConnection", xml(repository),
                        "minimumJavaVersion", target.minimumJavaVersion(),
                        "dependencies", block));
    }

    private static String modelLocation(JsonNode item) {
        return Plan.location(item);
    }

    private static ObjectNode modelRef(JsonNode provenance) {
        ObjectNode result = Json.object();
        result.put("coordinate", provenance.path("coordinate").asText());
        if (provenance.has("jsonPointer") && !provenance.path("jsonPointer").asText().isEmpty()) {
            result.put("jsonPointer", provenance.path("jsonPointer").asText());
        }
        return result;
    }

    private static final class Locations {
        final Map<String, JsonNode> provenances = new LinkedHashMap<>();
        final Map<String, JsonNode> shapes = new LinkedHashMap<>();
    }

    private static void add(Locations locations, JsonNode item) {
        JsonNode provenance = item.path("provenance");
        String place = modelLocation(item);
        JsonNode previous = locations.provenances.get(place);
        if (previous != null && !previous.equals(provenance)) {
            throw fail(
                    "model",
                    "RCJ1012",
                    place,
                    "ambiguous legacy plan coordinate; separate model coordinate and JSON Pointer are required");
        }
        locations.provenances.put(place, provenance);
    }

    private static void walk(Locations locations, JsonNode shape) {
        add(locations, shape);
        locations.shapes.putIfAbsent(modelLocation(shape), shape);
        for (JsonNode property : Json.list(shape.path("properties"))) {
            add(locations, property);
            walk(locations, property.path("shape"));
        }
        for (String name : List.of("items", "mapValues")) {
            if (shape.has(name)) {
                walk(locations, shape.get(name));
            }
        }
        for (JsonNode child : Json.list(shape.path("variants"))) {
            walk(locations, child);
        }
    }

    private static Locations modelLocations(JsonNode model) {
        Locations locations = new Locations();
        JsonNode vocabulary = model.path("vocabulary");
        for (String group :
                List.of("ownedDeclarations", "importedDeclarations", "interfaces", "conditionFields", "valueDomains")) {
            for (JsonNode item : Json.list(vocabulary.path(group))) {
                add(locations, item);
            }
        }
        for (JsonNode scope : Json.list(model.path("scopes"))) {
            if (scope.has("projection")) {
                walk(locations, scope.get("projection"));
            }
        }
        for (JsonNode schema : Json.list(model.path("schemas"))) {
            add(locations, schema);
            walk(locations, schema.path("projection"));
            for (JsonNode definition : Json.list(schema.path("definitions"))) {
                add(locations, definition);
                walk(locations, definition.path("shape"));
            }
        }
        return locations;
    }

    private static ObjectNode reference(TypeExpr expression, EmissionPlan plan) {
        ObjectNode result = Json.object();
        switch (expression.kind()) {
            case "object", "enum", "ref", "alias" -> result.put("type", plan.names().get(expression.symbolKey()));
            case "string" -> result.put("builtin", "String");
            case "boolean" -> result.put("builtin", "Boolean");
            case "integer" -> result.put("builtin", "Long");
            case "number" -> result.put("builtin", "Double");
            case "null" -> result.put("builtin", "Void");
            case "any" -> result.put("builtin", "Object");
            default -> throw new IllegalStateException("unplanned type kind " + expression.kind());
        }
        return result;
    }

    private static ArrayNode structuralTypes(EmissionPlan plan, Locations locations) {
        Map<String, String> contracts = new LinkedHashMap<>();
        for (DeclarationPlan item : plan.declarations()) {
            contracts.put(item.method(), item.coordinate());
        }
        for (ImportedDeclarationPlan item : plan.importedDeclarations()) {
            contracts.put(item.method(), item.coordinate());
        }
        List<ObjectNode> result = new ArrayList<>();
        for (TypePlan item : plan.types()) {
            JsonNode shape = locations.shapes.get(item.coordinate());
            String aliasKind = item.expression() == null ? "" : item.expression().kind();
            String construct;
            if (item.kind() == Kind.OBJECT) {
                construct = shape.path("kind").asText().equals("object") ? "object" : "wrapper";
            } else if (item.kind() == Kind.ENUM) {
                construct = "scalar";
            } else {
                construct = switch (aliasKind) {
                    case "array" -> "collection";
                    case "map" -> "map";
                    default -> "union";
                };
            }
            ObjectNode entry = Json.object();
            entry.set("modelRef", modelRef(locations.provenances.get(item.coordinate())));
            entry.put("sourceName", item.sourceName());
            entry.put("nativeName", item.name());
            entry.put("construct", construct);
            entry.put("file", item.name() + ".java");
            if (item.kind() == Kind.ENUM) {
                entry.put("underlying", "string");
                ArrayNode members = entry.putArray("members");
                for (Plan.Member member : item.members()) {
                    ObjectNode node = members.addObject();
                    node.set("modelRef", modelRef(locations.provenances.get(item.coordinate())));
                    node.put("nativeName", member.name());
                    node.put("value", member.value());
                }
            }
            if (item.kind() == Kind.OBJECT) {
                ArrayNode fields = entry.putArray("fields");
                for (FieldPlan field : item.fields()) {
                    ObjectNode node = fields.addObject();
                    node.set("modelRef", modelRef(locations.provenances.get(field.coordinate())));
                    node.put("sourceName", construct.equals("wrapper") ? item.sourceName() : field.sourceName());
                    node.put("nativeName", field.name());
                    node.put("required", field.required());
                    node.set("value", reference(field.typeExpr(), plan));
                    if (construct.equals("wrapper")) {
                        node.put("synthetic", true);
                    }
                }
                if (item.marker() != null) {
                    ObjectNode implemented = entry.putArray("implements").addObject();
                    implemented.put("declarationCoordinate", contracts.get(item.marker().method()));
                    implemented.put("markerMethod", item.marker().method());
                }
            }
            if (item.kind() == Kind.ALIAS) {
                if (construct.equals("collection") || construct.equals("map")) {
                    JsonNode child = shape.path(construct.equals("collection") ? "items" : "mapValues");
                    ObjectNode element = entry.putObject("element");
                    element.set("modelRef", modelRef(child.path("provenance")));
                    element.set("value", reference(item.expression().arguments().get(0), plan));
                } else {
                    ArrayNode variants = entry.putArray("variants");
                    List<JsonNode> children = Json.list(shape.path("variants"));
                    for (int index = 0; index < children.size(); index += 1) {
                        ObjectNode node = variants.addObject();
                        node.set("modelRef", modelRef(children.get(index).path("provenance")));
                        node.set("value", reference(item.expression().arguments().get(index), plan));
                    }
                }
            }
            result.add(entry);
        }
        result.sort(Comparator.comparing((ObjectNode node) -> node.path("nativeName").asText()));
        ArrayNode array = Json.MAPPER.createArrayNode();
        result.forEach(array::add);
        return array;
    }

    private static int text(String left, String right) {
        return Integer.signum(left.compareTo(right));
    }

    private static String manifest(EmissionPlan plan, JsonNode model) {
        Locations locations = modelLocations(model);
        String rootId = model.path("rootExtension").path("id").asText();
        Map<String, JsonNode> declarations = new LinkedHashMap<>();
        for (String group : List.of("ownedDeclarations", "importedDeclarations")) {
            for (JsonNode item : Json.list(model.path("vocabulary").path(group))) {
                declarations.put(item.path("kind").asText(), item);
            }
        }
        Map<List<String>, JsonNode> fields = new LinkedHashMap<>();
        for (JsonNode item : Json.list(model.path("vocabulary").path("conditionFields"))) {
            if (item.path("owner").asText().equals(rootId)) {
                fields.put(
                        List.of(item.path("kind").asText(), item.path("interfaceType").asText(""), item.path("path").asText()),
                        item);
            }
        }
        List<ObjectNode> rootBindings = new ArrayList<>();
        for (JsonNode schema : Json.list(model.path("schemas"))) {
            if (!schema.path("owner").asText().equals(rootId)) {
                continue;
            }
            String kind = schema.has("kind") ? schema.path("kind").asText() : schema.path("id").asText();
            if (!declarations.containsKey(kind)) {
                continue;
            }
            String interfaceType = schema.path("interfaceType").asText("");
            for (JsonNode property : Json.list(schema.path("projection").path("properties"))) {
                String name = property.path("name").asText();
                boolean isInterface = name.equals("interface") && !interfaceType.isEmpty();
                String sourceName = isInterface ? interfaceType : name;
                String nativeName = plan.names().get("type:field:" + schema.path("coordinate").asText() + ":" + name);
                if (nativeName == null) {
                    throw fail(
                            "model",
                            "RCJ1012",
                            schema.path("coordinate").asText(),
                            "root property '" + name + "' has no declaration field type");
                }
                JsonNode vocabularyField = fields.get(List.of(kind, interfaceType, name));
                String role = isInterface ? "interface" : vocabularyField != null ? "condition-field" : "schema-field";
                ObjectNode binding = Json.object();
                binding.put("role", role);
                binding.set("modelRef", modelRef(property.path("provenance")));
                binding.put("declarationCoordinate", declarations.get(kind).path("coordinate").asText());
                ObjectNode scope = binding.putObject("scope");
                scope.put("kind", kind);
                if (!interfaceType.isEmpty()) {
                    scope.put("interfaceType", interfaceType);
                }
                binding.put("sourceName", sourceName);
                binding.putArray("path").addObject().put("name", name);
                binding.putObject("value").put("type", nativeName);
                binding.put("schemaCoordinate", schema.path("coordinate").asText());
                if (role.equals("interface")) {
                    binding.put("fixedInterfaceType", interfaceType);
                }
                if (vocabularyField != null) {
                    binding.put("vocabularyCoordinate", vocabularyField.path("coordinate").asText());
                }
                rootBindings.add(binding);
            }
        }
        rootBindings.sort(
                (a, b) -> {
                    int order = text(a.path("declarationCoordinate").asText(), b.path("declarationCoordinate").asText());
                    if (order != 0) {
                        return order;
                    }
                    order = text(a.path("modelRef").path("coordinate").asText(), b.path("modelRef").path("coordinate").asText());
                    if (order != 0) {
                        return order;
                    }
                    return text(a.path("modelRef").path("jsonPointer").asText(""), b.path("modelRef").path("jsonPointer").asText(""));
                });

        ObjectNode document = Json.object();
        document.put("apiVersion", "runtimeconditions.io/bindings/v1alpha2");
        document.put("kind", "RuntimeConditionsBindingManifest");
        ObjectNode generated = document.putObject("generated");
        generated.put("nonEditable", true);
        generated.put("emitter", EMITTER_NAME + "@sha256:" + plan.target().emitterSha256());
        generated.put("version", EMITTER_VERSION);
        ObjectNode modelNode = document.putObject("model");
        modelNode.put("apiVersion", model.path("apiVersion").asText());
        modelNode.put("semanticSha256", plan.modelDigest());
        ObjectNode extension = document.putObject("extension");
        extension.put("id", rootId);
        extension.put("semanticSha256", model.path("rootExtension").path("semanticSha256").asText());
        ObjectNode pack = document.putObject("package");
        pack.put("language", "java");
        pack.put("coordinate", plan.target().coordinate());
        pack.put("name", plan.target().javaPackage());
        pack.put("version", plan.target().version());
        pack.put("minimumJavaVersion", plan.target().minimumJavaVersion());
        ArrayNode declared = document.putArray("declarations");
        for (DeclarationPlan item : plan.declarations()) {
            ObjectNode node = declared.addObject();
            node.set("modelRef", modelRef(locations.provenances.get(item.coordinate())));
            node.put("owner", rootId);
            node.put("sourceName", item.kind());
            node.put("function", item.function());
            node.put("functionClass", Plan.FUNCTIONS_CLASS);
            node.put("markerInterface", item.protocol());
            node.put("markerMethod", item.method());
            node.put("file", Plan.FUNCTIONS_CLASS + ".java");
        }
        ArrayNode contracts = document.putArray("importedMarkerContracts");
        for (ImportedDeclarationPlan item : plan.importedDeclarations()) {
            ObjectNode node = contracts.addObject();
            node.set("modelRef", modelRef(locations.provenances.get(item.coordinate())));
            node.put("owner", item.owner());
            node.put("sourceName", item.kind());
            node.put("markerInterface", item.protocol());
            node.put("markerMethod", item.method());
            node.put("providerPackage", item.providerPackage().coordinate());
        }
        ArrayNode roots = document.putArray("rootBindings");
        rootBindings.forEach(roots::add);
        document.set("types", structuralTypes(plan, locations));

        Map<String, Object> map = Json.MAPPER.convertValue(document, new TypeReference<LinkedHashMap<String, Object>>() {});
        DumpSettings settings =
                DumpSettings.builder()
                        .setDefaultFlowStyle(FlowStyle.BLOCK)
                        .setIndent(2)
                        .setIndicatorIndent(2)
                        .setIndentWithIndicator(true)
                        .setWidth(Integer.MAX_VALUE)
                        .setSplitLines(false)
                        .build();
        return "# " + header(model) + "\n" + new Dump(settings).dumpToString(map);
    }

    public static Map<String, String> renderResources(EmissionPlan plan, JsonNode model) {
        if (plan.target().emitterSha256().isEmpty()) {
            throw fail(
                    "package-config",
                    "RCJ1006",
                    plan.target().packageKey(),
                    "emitterSha256 is required when emitting package resources",
                    "/emitterSha256");
        }
        if (!model.path("metadata").path("semanticSha256").asText().equals(plan.modelDigest())
                || !model.path("rootExtension").path("id").asText().equals(plan.target().rootExtension())) {
            throw fail("model", "RCJ1003", "model", "emission plan does not match supplied model");
        }
        JsonNode root = model.path("rootExtension");
        List<JsonNode> roots = new ArrayList<>();
        for (JsonNode item : Json.list(model.path("extensions"))) {
            if (item.path("id").asText().equals(root.path("id").asText())) {
                roots.add(item);
            }
        }
        if (roots.size() != 1
                || !roots.get(0).path("semanticSha256").asText().equals(root.path("semanticSha256").asText())) {
            throw fail(
                    "model",
                    "RCJ1003",
                    root.path("id").asText(),
                    "root extension digest does not match model extension closure");
        }
        Map<String, String> files = new TreeMap<>();
        files.put("pom.xml", pom(plan, model));
        files.put(MANIFEST_PATH, manifest(plan, model));
        return files;
    }
}
