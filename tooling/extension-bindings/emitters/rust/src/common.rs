use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use crate::diag::*;

pub const NAME: &str = "runtimeconditions-binding-emitter-rust";

pub const VERSION: &str = env!("CARGO_PKG_VERSION");

pub const MANIFEST: &str = "runtimeconditions/runtimeconditions.bindings.yaml";

pub fn s<'a>(v: &'a Value, k: &str) -> &'a str {
    v[k].as_str().unwrap_or("")
}

pub fn arr<'a>(v: &'a Value, k: &str) -> &'a [Value] {
    v[k].as_array().map_or(&[], |a| a.as_slice())
}

pub fn loc(v: &Value) -> String {
    match s(&v["provenance"], "jsonPointer") {
        "" => s(&v["provenance"], "coordinate").into(),
        j => format!("{}{SEP}{j}", s(&v["provenance"], "coordinate")),
    }
}

pub fn mref(p: &Value) -> Value {
    match s(p, "jsonPointer") {
        "" => json!({"coordinate": s(p, "coordinate")}),
        j => json!({"coordinate": s(p, "coordinate"), "jsonPointer": j}),
    }
}

pub fn marker_method(owner: &str, coord: &str) -> String {
    let d = Sha256::new().chain_update(owner).chain_update([0]).chain_update(coord).finalize();
    format!("rc_marker_{}", &format!("{d:x}")[..16])
}

pub fn header(m: &Value) -> String {
    format!("Code generated by {NAME} {VERSION} from model {}; DO NOT EDIT.", s(&m["metadata"], "semanticSha256"))
}
